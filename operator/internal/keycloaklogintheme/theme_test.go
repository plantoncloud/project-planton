// The ConfigMap the operator materializes this theme into has a hard 1MiB
// ceiling; leave real headroom so adding an artifact never becomes a
// production surprise.
const configMapSizeBudget = 512 * 1024

var acme = EmailFacts{BrandName: "Acme Platform", ConsoleURL: "https://planton.acme.com", ReplyTo: "it-help@acme.com"}

func TestFilesCarriesEveryArtifact(t *testing.T) {
	files := Files(acme)

	for _, p := range []string{
		PathThemeProperties, PathStylesCSS, PathLogoSVG, PathInterFontWOFF2,
		PathEmailThemeProperties, PathEmailHTMLLayout, PathEmailTextLayout, PathEmailMessages,
		"email/html/password-reset.ftl", "email/text/password-reset.ftl",
		"email/html/executeActions.ftl", "email/text/executeActions.ftl",
		"email/html/email-verification.ftl", "email/text/email-verification.ftl",
		"email/html/email-test.ftl", "email/text/email-test.ftl",
	} {
		content, ok := files[p]
		if !ok {
			t.Fatalf("Files() is missing %q", p)
		}
		if len(content) == 0 {
			t.Fatalf("Files()[%q] is empty", p)
		}
	}
	for p := range files {
		if strings.HasPrefix(p, "theme/") || strings.HasPrefix(p, "/") {
			t.Errorf("path %q is not relative to the theme root", p)
		}
		if !strings.HasPrefix(p, "login/") && !strings.HasPrefix(p, "email/") {
			t.Errorf("path %q is outside the two theme types this theme ships", p)
		}
	}
}

func TestThemePropertiesShape(t *testing.T) {
	props := string(Files(acme)[PathThemeProperties])

	for _, want := range []string{
		// Extending the bundled theme is the safety property: unoverridden
		// screens keep working. A parent change is a deliberate decision.
		"parent=keycloak.v2",
		// The parent's stylesheet must stay in the list (child-first lookup
		// falls back to the parent for it), ours appended after.
		"styles=css/styles.css css/planton.css",
		// The OS must not flip the page out of the dark design.
		"darkMode=false",
	} {
		if !strings.Contains(props, want) {
			t.Errorf("theme.properties missing %q", want)
		}
	}
}

func TestEmailThemePropertiesCarryTheInstallsFacts(t *testing.T) {
	props := string(Files(acme)[PathEmailThemeProperties])

	for _, want := range []string{
		// Inheriting Keycloak's bundled email type keeps every message it can
		// send renderable; this theme overrides the layout and a few bodies.
		"parent=keycloak",
		"brandName=Acme Platform",
		"consoleUrl=https://planton.acme.com",
		"consoleHost=planton.acme.com",
		"replyTo=it-help@acme.com",
	} {
		if !strings.Contains(props, want) {
			t.Errorf("email/theme.properties missing %q in:\n%s", want, props)
		}
	}

	bare := string(Files(EmailFacts{BrandName: "Planton"})[PathEmailThemeProperties])
	for _, want := range []string{"brandName=Planton\n", "consoleUrl=\n", "consoleHost=\n", "replyTo=\n"} {
		if !strings.Contains(bare, want) {
			t.Errorf("an install with no console and no reply-to must still write %q (empty is honest) in:\n%s", want, bare)
		}
	}

	multiline := string(Files(EmailFacts{BrandName: "Acme\nPlatform"})[PathEmailThemeProperties])
	if !strings.Contains(multiline, "brandName=Acme Platform\n") {
		t.Errorf("a newline in a fact must not start a new property: %q", multiline)
	}
}

