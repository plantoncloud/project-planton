func TestHashIsDeterministicAndFollowsTheFacts(t *testing.T) {
	first := Hash(acme)
	second := Hash(acme)
	if first != second {
		t.Fatalf("Hash() is not deterministic: %q vs %q", first, second)
	}
	if len(first) != 64 {
		t.Fatalf("Hash() is not a sha256 hex string: %q", first)
	}
	renamed := acme
	renamed.BrandName = "Acme Cloud"
	if Hash(renamed) == first {
		t.Errorf("a changed brand name must change the hash: the identity pod rolls to pick up what its emails say")
	}
}

func TestTotalSizeFitsTheConfigMapBudget(t *testing.T) {
	total := 0
	for _, content := range Files(acme) {
		total += len(content)
	}
	if total > configMapSizeBudget {
		t.Fatalf("theme totals %d bytes, over the %d budget (ConfigMap ceiling is 1MiB; keep headroom)", total, configMapSizeBudget)
	}
}
