func TestEmailLayoutIsGeneratedFreeMarkerReadingTheFacts(t *testing.T) {
	files := Files(acme)
	html := string(files[PathEmailHTMLLayout])
	text := string(files[PathEmailTextLayout])

	for name, layout := range map[string]string{"html": html, "text": text} {
		if !strings.Contains(layout, "Generated by @planton/email-templates") {
			t.Errorf("%s layout is not the generated artifact; run the platform's `make email-templates`", name)
		}
		if strings.Contains(layout, "{{") || strings.Contains(layout, "__FTL_") {
			t.Errorf("%s layout carries compile-time syntax: %s", name, layout)
		}
		for _, property := range []string{"properties.brandName", "properties.consoleUrl", "properties.consoleHost", "properties.replyTo"} {
			if !strings.Contains(layout, property) {
				t.Errorf("%s layout does not read %s", name, property)
			}
		}
	}
	if !strings.HasPrefix(html, `<#ftl output_format="HTML">`) {
		t.Errorf("the html layout must declare HTML output so every interpolation is escaped")
	}
	for _, macro := range []string{`emailLayout preview=""`, "heading", "paragraph", "muted", "button href", "fallbackLink href", "facts", "fact label", "code"} {
		if !strings.Contains(html, "<#macro "+macro+">") {
			t.Errorf("html layout is missing macro %q", macro)
		}
	}
	if !strings.Contains(text, "<#macro textLayout>") {
		t.Errorf("text layout is missing the textLayout macro")
	}
	// A credential-adjacent email must fetch nothing from third parties; the
	// doctype's DTD identifier is a name, not a fetch.
	withoutDoctype := regexp.MustCompile(`<!DOCTYPE[^>]*>`).ReplaceAllString(html, "")
	if strings.Contains(withoutDoctype, "http://") || strings.Contains(withoutDoctype, "https://") {
		t.Errorf("the html layout references an external URL; the frame must be self-contained")
	}
}

func TestEveryMessageTemplateComposesTheLayout(t *testing.T) {
	files := Files(acme)
	importsLayout := regexp.MustCompile(`<#import "template\.ftl" as layout>`)
	for p, content := range files {
		if !strings.HasPrefix(p, "email/html/") && !strings.HasPrefix(p, "email/text/") {
			continue
		}
		if strings.HasSuffix(p, "/template.ftl") {
			continue
		}
		body := string(content)
		if !importsLayout.MatchString(body) {
			t.Errorf("%s does not import the layout; every identity email wears the same frame", p)
		}
		want := "<@layout.emailLayout"
		if strings.HasPrefix(p, "email/text/") {
			want = "<@layout.textLayout>"
			if !strings.HasPrefix(body, `<#ftl output_format="plainText">`) {
				t.Errorf("%s must declare plainText output", p)
			}
		}
		if !strings.Contains(body, want) {
			t.Errorf("%s does not compose %s", p, want)
		}
		if !strings.Contains(body, "properties.brandName") {
			t.Errorf("%s never names the install (properties.brandName)", p)
		}
		if strings.Contains(body, "realmName") {
			t.Errorf("%s names the realm; emails name the install's brand, never the realm", p)
		}
	}
	for _, message := range []string{"password-reset", "executeActions", "email-verification", "email-test"} {
		if _, ok := files["email/html/"+message+".ftl"]; !ok {
			t.Errorf("no html body for %s", message)
		}
		if _, ok := files["email/text/"+message+".ftl"]; !ok {
			t.Errorf("no text body for %s (Keycloak renders both parts)", message)
		}
	}
}

