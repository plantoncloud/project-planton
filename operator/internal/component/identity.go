const defaultIdentityRealm = "planton"

// Identity deploys the platform's bundled identity server (Keycloak) and
// provisions it declaratively: realm, console OIDC client, and the first
// admin user are generated by the operator with credentials in Secrets, so
// every install has working multi-user sign-in with zero external identity
// setup.
//
// Identity is not switchable -- every install deploys it. "Deploy Planton"
// always yields an authenticated platform: at the public hostname when
// ingress is the front door, or through the gateway's port-forward URL when
// it is not. An unauthenticated platform is unrepresentable.
type Identity struct{ Base }

func (id *Identity) Name() string { return "identity" }

func (id *Identity) Dependencies(_ *v1.PlantonPlatform) []string {
	return []string{"postgresql"}
}

func (id *Identity) IsEnabled(_ *v1.PlantonPlatform) bool { return true }

func (id *Identity) Reconcile(ctx context.Context, c client.Client, _ *runtime.Scheme, planton *v1.PlantonPlatform) (Result, error) {
	log := logf.FromContext(ctx).WithValues("component", id.Name())
	ownerRef := id.OwnerReferenceFor(planton)

	// Resolve PlantonIdentityProvider bindings first: the resolution needs
	// only the Kubernetes API, so identity-config authors see their
	// boundPlatform verdict even while Keycloak is still booting.
	boundIdp, err := id.reconcileIdentityProviderBindings(ctx, c, planton)
	if err != nil {
		return Result{}, fmt.Errorf("resolving identity provider bindings: %w", err)
	}

	// The realm-state record: what the operator last handed the realm
	// (credential fingerprints, discovered endpoints). Read once here; the
	// steps below advance their own fields in memory; written once at the
	// end of the pass when it changed.
	recorded := id.readRealmState(ctx, c, planton)
	record := recorded

	// Translate the bound manifest (and its referenced Secrets) into the
	// realm reconciler's desired federation state. A build failure is the
	// MANIFEST's status to carry -- the identity server keeps serving the
	// users it already has, and the live federation is left untouched.
	var fedBuild *federationBuild
	if boundIdp != nil {
		fedBuild = id.buildFederationState(ctx, c, planton, boundIdp, recorded)
		if fedBuild.buildErr != "" {
			id.setFederationStatus(ctx, c, boundIdp, metav1.Condition{
				Type: v1.ConditionProvisioned, Status: metav1.ConditionFalse,
				Reason:             "DesiredStateUnavailable",
				Message:            fedBuild.buildErr,
				ObservedGeneration: boundIdp.Generation,
			}, nil)
		}
	}

	// Publish the federation facts projection FIRST thing every pass --
	// before any readiness gate can early-return -- so the ConfigMap the
	// control plane mounts provably exists on every install from the first
	// pass (content is configured=false until a manifest binds). Re-run
	// after verification below so fresh verdicts project the same pass.
	id.projectFederationFacts(ctx, c, planton, boundIdp, false)

	// The issuer URL, redirect URIs, and Keycloak's own hostname all derive
	// from the ONE front-door URL: the ingress public URL, or the gateway's
	// deterministic localhost URL. In auto-hostname mode it resolves in the
	// ingress component's pass and reaches here through in-memory status.
	publicURL, resolved := frontDoorURL(planton)
	if !resolved || publicURL == "" {
		return Result{Ready: false,
			Message: "waiting for the public URL to resolve (see the ingress component) before configuring the identity server"}, nil
	}

	// Master-realm bootstrap admin password (Keycloak's own admin console).
	// Read back because the same credential authenticates the realm
	// reconciler below -- the operator holds the master Secret in this
	// namespace regardless, so a derived realm-management credential would
	// only add a rotation surface (see the realm reconciliation design in
	// the superseding identity ADR).
	bootstrapAdmin, err := id.EnsureAndReadCredential(ctx, c,
		resources.IdentityBootstrapAdminSecretName(planton.Name), planton.Namespace,
		map[string]string{resources.IdentityBootstrapAdminPasswordKey: ""}, ownerRef)
	if err != nil {
		return Result{}, fmt.Errorf("ensuring identity bootstrap admin Secret: %w", err)
	}

	adminEmail := identityAdminEmail(planton)
	adminUser, err := id.ensureSeededAdminCredential(ctx, c, planton, adminEmail, publicURL, ownerRef)
	if err != nil {
		return Result{}, err
	}

	oidcClient, err := id.EnsureAndReadCredential(ctx, c,
		resources.IdentityOIDCClientSecretName(planton.Name), planton.Namespace,
		map[string]string{resources.IdentityOIDCClientSecretKey: ""}, ownerRef)
	if err != nil {
		return Result{}, fmt.Errorf("ensuring identity OIDC client Secret: %w", err)
	}

	usersClient, err := id.EnsureAndReadCredential(ctx, c,
		resources.IdentityUsersClientSecretName(planton.Name), planton.Namespace,
		map[string]string{resources.IdentityOIDCClientSecretKey: ""}, ownerRef)
	if err != nil {
		return Result{}, fmt.Errorf("ensuring identity users client Secret: %w", err)
	}

	// First-run setup mode: with no admin declared, the realm starts with no
	// person in it, and the console's setup page creates the first admin. The
	// setup code is the cluster-access proof that page demands -- generated
	// here (before the control plane renders, which references it by name)
	// and read by the person with the exact command the status prints below.
	if adminEmail == "" {
		if err := id.EnsureCredentialSecret(ctx, c,
			resources.IdentitySetupCodeSecretName(planton.Name), planton.Namespace,
			resources.IdentitySetupCodeSecretKey, ownerRef); err != nil {
			return Result{}, fmt.Errorf("ensuring first-run setup code Secret: %w", err)
		}
	}

	realmImport, err := resources.IdentityRealmImport(resources.IdentityRealmImportConfig{
		Realm:         identityRealm(planton),
		PublicURL:     publicURL,
		ClientSecret:  oidcClient[resources.IdentityOIDCClientSecretKey],
		UsersSecret:   usersClient[resources.IdentityOIDCClientSecretKey],
		AdminEmail:    adminUser["email"],
		AdminPassword: adminUser["password"],
	})
	if err != nil {
		return Result{}, fmt.Errorf("rendering realm import: %w", err)
	}

	importSecret := resources.NewCredentialSecret(
		resources.IdentityRealmImportSecretName(planton.Name), planton.Namespace,
		resources.IdentityRealmImportKey, string(realmImport), ownerRef)
	if err := id.ApplyTypedObject(ctx, c, importSecret); err != nil {
		return Result{}, fmt.Errorf("applying realm import Secret: %w", err)
	}

	// The login theme rides a ConfigMap (applied before the Deployment that
	// mounts it) so the sign-in pages ship in the product design system on
	// the unmodified official Keycloak image.
	themeConfigMap, err := resources.IdentityThemeConfigMap(planton.Name, planton.Namespace, ownerRef)
	if err != nil {
		return Result{}, fmt.Errorf("building identity theme ConfigMap: %w", err)
	}
	if err := id.ApplyTypedObject(ctx, c, themeConfigMap); err != nil {
		return Result{}, fmt.Errorf("applying identity theme ConfigMap: %w", err)
	}

	importHash := sha256.Sum256(realmImport)

	cfg := resources.IdentityConfig{
		CRName:          planton.Name,
		Namespace:       planton.Namespace,
		OwnerRef:        ownerRef,
		Realm:           identityRealm(planton),
		PublicURL:       publicURL,
		RealmImportHash: hex.EncodeToString(importHash[:]),
		ThemeHash:       resources.IdentityThemeHash(),
		PostgreSQL:      resources.PostgreSQLConnection(planton.Name, planton.Namespace),
	}
	if fedBuild != nil && fedBuild.caBundleSecretName != "" {
		// The directory's private CA rides into Keycloak's truststore; the
		// hash annotation rolls the pod when the CA rotates (truststores
		// are read at server start).
		cfg.CABundleSecretName = fedBuild.caBundleSecretName
		cfg.CABundleSecretKey = fedBuild.caBundleSecretKey
		cfg.CABundleHash = fedBuild.caBundleHash
	}

	// The platform's email declaration, as the identity server's own mail
	// settings (see identity_email.go): the relay's private CA joins the
	// truststore here, the relay itself is converged onto the realm below.
	emailBuild := id.buildEmailRealmState(ctx, c, planton, recorded)
	emailBuild.applyTruststore(&cfg)
	if planton.Spec.Identity != nil && planton.Spec.Identity.Image != nil {
		cfg.ImageRepository = planton.Spec.Identity.Image.Repository
		cfg.ImageTag = planton.Spec.Identity.Image.Tag
	}

	if err := id.ApplyTypedObject(ctx, c, resources.IdentityDeployment(cfg)); err != nil {
		return Result{}, fmt.Errorf("applying Identity Deployment: %w", err)
	}
	if err := id.ApplyTypedObject(ctx, c, resources.IdentityService(planton.Name, planton.Namespace, ownerRef)); err != nil {
		return Result{}, fmt.Errorf("applying Identity Service: %w", err)
	}

	ready, err := id.IsDeploymentReady(ctx, c, resources.IdentityDeploymentName(planton.Name), planton.Namespace)
	if err != nil {
		return Result{}, fmt.Errorf("checking Identity readiness: %w", err)
	}
	if !ready {
		log.Info("Identity server not ready")
		return Result{Ready: false, Message: "Waiting for the identity server (first boot imports the sign-in realm)"}, nil
	}

	// The realm reconciler: the first-boot import above is the bootstrap;
	// this is the contract. It converges exactly the operator-owned set on
	// the LIVE realm -- the three Planton clients (redirect URIs re-derived
	// from the CURRENT front door, so a deliberate hostname change heals
	// instead of stranding sign-in), the security-posture realm settings,
	// the identity server's mail settings from the platform's email
	// declaration, and the federation state the bound identity manifest
	// declares -- and never touches admin-created state. A failed pass
	// reports not-ready and retries on the next reconcile, the same posture
	// as the OpenFGA bootstrap.
	serverRoot := resources.IdentityInternalServerRootURL(planton.Name, planton.Namespace)
	adminPassword := bootstrapAdmin[resources.IdentityBootstrapAdminPasswordKey]
	report, err := keycloak.Converge(ctx, keycloak.ConvergeInput{
		OwnedRealmInput: keycloak.OwnedRealmInput{
			Realm:               identityRealm(planton),
			PublicURL:           publicURL,
			ConsoleClientSecret: oidcClient[resources.IdentityOIDCClientSecretKey],
			UsersClientSecret:   usersClient[resources.IdentityOIDCClientSecretKey],
			Email:               emailBuild.email,
		},
		Federation:    federationForConverge(boundIdp, fedBuild),
		ServerRoot:    serverRoot,
		AdminUsername: resources.IdentityBootstrapAdminUsername,
		AdminPassword: adminPassword,
		HTTPClient:    &http.Client{Timeout: httpClientTimeout},
	})
	if err != nil {
		log.Error(err, "Realm reconciliation failed; will retry on next reconcile")
		if boundIdp != nil {
			id.setFederationStatus(ctx, c, boundIdp, metav1.Condition{
				Type: v1.ConditionProvisioned, Status: metav1.ConditionFalse,
				Reason:             "ConvergeFailed",
				Message:            "the identity server's realm could not be reconciled: " + err.Error(),
				ObservedGeneration: boundIdp.Generation,
			}, nil)
		}
		return Result{Ready: false, Message: fmt.Sprintf(
			"Identity server is up but its sign-in realm could not be reconciled: %v", err)}, nil
	}
	logRealmRepairs(log, report)

	// The relay credential is on the realm now (written on rotation, or
	// carried by a settings write); record its fingerprint so the next pass
	// reads steady state.
	emailBuild.advanceRecord(&record)

	// Verification + the manifest's Provisioned verdicts, on the manifest's
	// cadence (never the reconcile's -- the checks probe the company's
	// directory). When verification ran, re-project the facts so the fresh
	// verdicts reach the control plane's mounted file the same pass.
	if boundIdp != nil && fedBuild.buildErr == "" {
		verified := id.finishFederation(ctx, c, boundIdp, fedBuild, report, keycloak.VerifyInput{
			Realm:            identityRealm(planton),
			ServerRoot:       serverRoot,
			AdminUsername:    resources.IdentityBootstrapAdminUsername,
			AdminPassword:    adminPassword,
			HTTPClient:       &http.Client{Timeout: httpClientTimeout},
			SeededAdminEmail: adminEmail,
		}, &record)
		if verified {
			id.projectFederationFacts(ctx, c, planton, boundIdp, true)
		}
	}

	id.persistRealmState(ctx, c, planton, recorded, record)

	log.Info("Identity server ready")

	if adminEmail == "" {
		return Result{Ready: true, Message: identitySetupModeReadyMessage(planton.Name, planton.Namespace, publicURL)}, nil
	}
	return Result{Ready: true, Message: identityDeclaredAdminReadyMessage(planton.Name, publicURL)}, nil
}

// ensureSeededAdminCredential ensures (and reads back) the seeded admin
// user's one-time password Secret when an adminEmail is declared -- the
// credential is baked into the realm import. The Secret carries the LOGIN
// (the fixed short username) and the EMAIL (the real person the grants key
// on) separately. When no adminEmail is declared, no user is seeded at all
// -- there is deliberately no generic pre-baked identity, and the Ready
// message states plainly how sign-in gets its first user.
func (id *Identity) ensureSeededAdminCredential(ctx context.Context, c client.Client, planton *v1.PlantonPlatform, adminEmail, publicURL string, ownerRef *metav1.OwnerReference) (map[string]string, error) {
	if adminEmail == "" {
		return map[string]string{}, nil
	}
	adminUser, err := id.EnsureAndReadCredential(ctx, c,
		resources.IdentityAdminUserSecretName(planton.Name), planton.Namespace,
		map[string]string{
			"username": resources.IdentityAdminUsername,
			"email":    adminEmail,
			"password": "",
		}, ownerRef)
	if err != nil {
		return nil, fmt.Errorf("ensuring identity admin user Secret: %w", err)
	}
	// The credential is one-time (consumed at first sign-in), and the
	// Secret is where a person goes looking when sign-in later fails --
	// make it say so right there. Applied every reconcile (annotations
	// only; the credential data is untouched) so existing installs gain
	// the note too. Must run AFTER the ensure above: annotating a
	// missing Secret would create a data-less shell.
	if err := id.EnsureSecretAnnotations(ctx, c,
		resources.IdentityAdminUserSecretName(planton.Name), planton.Namespace,
		map[string]string{
			resources.IdentityOneTimePasswordAnnotation: resources.IdentityOneTimePasswordNote(planton.Name, publicURL),
		}); err != nil {
		return nil, fmt.Errorf("annotating identity admin user Secret: %w", err)
	}
	return adminUser, nil
}

// logRealmRepairs reports one convergence pass in the grant-reconciler
// idiom: quiet when clean, one line per repair when it repaired.
func logRealmRepairs(log logr.Logger, report *keycloak.Report) {
	if report.Clean() {
		log.V(1).Info("Realm converged, nothing to repair")
		return
	}
	for _, repair := range report.Repairs {
		log.Info("Realm repaired", "repair", repair)
	}
}

// The two Ready-message arms live side by side as pure builders so their
// symmetry is visible and their content is unit-testable: both name the
// credential's one-time nature and the same recovery path (the identity
// server's own admin console, guarded by the bootstrap-admin Secret the
// operator already generates).

// identitySetupModeReadyMessage covers first-run setup mode: the realm has no
// person yet by design; the status names the whole journey -- where setup
// happens, where the code lives, and the lost-password recovery path.
func identitySetupModeReadyMessage(crName, namespace, publicURL string) string {
	return fmt.Sprintf(
		"Identity server ready; open the console -- the first visitor creates the admin account "+
			"using the setup code (read it with: %s). If the one-time password shown at setup is lost, "+
			"manage users in the identity server's admin console at %s%s (credentials in Secret %s)",
		resources.IdentitySetupCodeHint(crName, namespace),
		publicURL, resources.IdentityPathPrefix,
		resources.IdentityBootstrapAdminSecretName(crName))
}

// identityDeclaredAdminReadyMessage covers the declared-admin (GitOps
// override) arm. The password in the credentials Secret is consumed at the
// admin's first sign-in, so the message says so -- otherwise a person
// re-reading the Secret later gets a stale password and a bare "invalid
// username or password" at the sign-in form, with no way to know why.
func identityDeclaredAdminReadyMessage(crName, publicURL string) string {
	return fmt.Sprintf(
		"Identity server ready; first admin sign-in credentials are in Secret %s. "+
			"The password is one-time -- consumed at the admin's first sign-in (they set their own). "+
			"If sign-in later fails with 'invalid username or password', manage users in the identity "+
			"server's admin console at %s%s (credentials in Secret %s)",
		resources.IdentityAdminUserSecretName(crName),
		publicURL, resources.IdentityPathPrefix,
		resources.IdentityBootstrapAdminSecretName(crName))
}

// identityRealm returns the configured realm name or the default.
func identityRealm(planton *v1.PlantonPlatform) string {
	if planton.Spec.Identity != nil && planton.Spec.Identity.Realm != "" {
		return planton.Spec.Identity.Realm
	}
	return defaultIdentityRealm
}

// identityAdminEmail returns the configured first-admin login, or empty when
// none is declared. There is deliberately NO generic default identity
// ("admin@planton.local"-style): the first admin is a real person, named in
// the manifest -- or nobody, until a first-run setup flow creates them.
func identityAdminEmail(planton *v1.PlantonPlatform) string {
	if planton.Spec.Identity != nil {
		return planton.Spec.Identity.AdminEmail
	}
	return ""
}
